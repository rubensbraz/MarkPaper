/**
 * Main class responsible for parsing raw Markdown text into HTML.
 * It handles state management for nested blocks (lists, code, tables).
 * The only public method is parse(); everything else is internal.
 */
class MarkPaperParser {
  /** Initializes the parser. */
  constructor() {
    this.reset();
  }

  /**
   * Resets the internal state of the parser.
   * Must be called before parsing a new file.
   * @private
   */
  reset() {
    this.html = '';
    this.globalFigureNum = 0;

    // Section numbering state
    this.chapterNum = 0;
    this.sectionNum = 0;
    this.minorHeadingNum = 0; // Unique anchor counter for H4-H6
    this.currentSectionLevel = 0; // 1=h1, 2=h2...

    // Footnote state
    this.footnotesDef = {};        // Stores footnote content (id -> content)
    this.sectionFootnotes = [];    // Tracks footnotes used in the current section

    // Block context state
    this.state = {
      inCodeBlock: false, codeFence: '', codeLang: '', codeBuffer: [],
      inMathBlock: false, mathBuffer: [],
      inTable: false, tableHeader: null, tableRows: [], tableAlign: [],
      inBlockquote: false, blockquoteBuffer: [],
      inAlert: false, alertType: '', alertBuffer: [],
      listStack: [] // Nested list levels (ListStackItem[])
    };
  }

  /**
   * The main method to convert Markdown to HTML.
   * @param {string} markdown - The raw Markdown text.
   * @returns {string} - The compiled and sanitized HTML string.
   * @example
   * const html = new MarkPaperParser().parse('**Hello**');
   * // -> '<p><strong>Hello</strong></p>' followed by the footer markup
   */
  parse(markdown) {
    this.reset();

    const rawLines = markdown.split(/\r?\n/);
    // Preprocess to extract footnote definitions from the bottom/text
    const lines = this.preprocess(rawLines);

    for (let i = 0; i < lines.length; i++) {
      const line = lines[i].trimEnd();

      // 1. Handle Code Blocks (Highest priority)
      if (this.processCodeBlock(line)) continue;
      if (this.state.inCodeBlock) {
        this.state.codeBuffer.push(line);
        continue;
      }

      // 2. Handle Math Blocks
      if (this.processMathBlock(line)) continue;
      if (this.state.inMathBlock) {
        this.state.mathBuffer.push(line);
        continue;
      }

      // 3. Handle Empty Lines (Triggers block closures)
      if (line.trim() === '') {
        this.processEmptyLine();
        continue;
      }

      // 4. Handle Indented Code Blocks
      if (this.processIndentedCode(line)) continue;

      // 5. Handle Headings
      if (this.processHeadings(line, i, lines)) continue;

      // 6. Handle Horizontal Rules
      if (CONFIG.PATTERNS.HR.test(line.trim())) {
        this.closeAllBlocks();
        this.html += '<hr>\n';
        continue;
      }

      // 7. Handle Lists
      if (this.processLists(line)) continue;

      // 8. Handle Tables
      if (this.processTables(line, i, lines)) continue;

      // 9. Handle Blockquotes & Alerts
      if (this.processQuotesAndAlerts(line)) continue;

      // 10. Handle Standalone Images
      if (this.processStandaloneImage(line)) continue;

      // 11. Handle Video Embeds (YouTube/Vimeo)
      if (this.processMediaEmbeds(line)) continue;

      // 12. Handle Raw Block HTML
      if (this.processBlockHtml(line)) continue;

      // 13. Default: Paragraph
      // Close strictly block-level elements before starting a paragraph
      this.closeList();
      this.closeTable();
      this.closeBlockquote();
      this.closeAlert();

      this.html += `<p>${this.escapeInline(line)}</p>\n`;
    }

    // Final cleanup (close any open blocks at EOF)
    this.closeAllBlocks();
    this.appendSectionFootnotes();
    this.html += this.generateFooter();

    return this.html;
  }

  /**
   * Pre-processes lines to extract footnote definitions.
   * Definitions are stored and removed from the main flow.
   * @private
   * @param {string[]} lines - The array of markdown lines.
   * @returns {string[]} - The filtered array of lines.
   */
  preprocess(lines) {
    const cleanedLines = [];
    for (let i = 0; i < lines.length; i++) {
      const line = lines[i];
      const fnMatch = line.match(CONFIG.PATTERNS.FOOTNOTE_DEF);
      if (fnMatch) {
        this.footnotesDef[fnMatch[1]] = fnMatch[2];
        continue;
      }
      cleanedLines.push(line);
    }
    return cleanedLines;
  }

  // --- Block Handlers ---

  /**
   * Detects and manages the state of fenced code blocks (```).
   * @private
   * @param {string} line - Current line.
   * @returns {boolean} - True if line was consumed.
   */
  processCodeBlock(line) {
    const match = line.match(CONFIG.PATTERNS.FENCE_START);
    if (match) {
      const fence = match[1];
      const lang = match[2];
      if (this.state.inCodeBlock) {
        // Only a fence identical to the opening one closes the block
        if (fence === this.state.codeFence) {
          this.flushCodeBlock();
          return true;
        }
        return false;
      } else {
        // Start new block
        this.closeAllBlocks();
        this.state.inCodeBlock = true;
        this.state.codeFence = fence;
        this.state.codeLang = lang;
        this.state.codeBuffer = [];
        return true;
      }
    }
    return false;
  }

  /**
   * Detects and manages math blocks ($$).
   * @private
   * @param {string} line - Current line.
   * @returns {boolean} - True if line was consumed.
   */
  processMathBlock(line) {
    // Handle inline display math: $$...$$ on a single line
    const singleLineMatch = line.match(CONFIG.PATTERNS.MATH_BLOCK_SINGLE);
    if (singleLineMatch && !this.state.inMathBlock) {
      this.closeAllBlocks();
      this.html += this.renderKaTeX(singleLineMatch[1], true);
      return true;
    }
    if (CONFIG.PATTERNS.MATH_BLOCK_START.test(line)) {
      if (this.state.inMathBlock) {
        this.flushMathBlock();
        return true;
      } else {
        this.closeAllBlocks();
        this.state.inMathBlock = true;
        this.state.mathBuffer = [];
        return true;
      }
    }
    return false;
  }

  /**
   * Handles indented code blocks (4 spaces or tab).
   * Indented list items are excluded so nested lists keep working.
   * @private
   * @param {string} line - Current line.
   * @returns {boolean} - True if line was consumed.
   */
  processIndentedCode(line) {
    if ((line.startsWith('    ') || line.startsWith('\t')) &&
      !CONFIG.PATTERNS.LIST_UL.test(line) &&
      !CONFIG.PATTERNS.LIST_OL.test(line)) {
      this.closeList();
      const codeText = line.replace(/^(    |\t)/, '');
      this.html += `<div class="code-block-container"><button class="copy-btn">${CONFIG.STRINGS.COPY}</button><pre><code class="language-plaintext">${this.escapeHTML(codeText)}</code></pre></div>\n`;
      return true;
    }
    return false;
  }

  /**
   * Processes headings (#) and metadata blocks at the top of the file.
   * @private
   * @param {string} line - Current line.
   * @param {number} index - Current line index.
   * @param {string[]} lines - All lines (to read ahead for metadata).
   * @returns {boolean} - True if line was consumed.
   */
  processHeadings(line, index, lines) {
    const h1Match = line.match(CONFIG.PATTERNS.H1);
    if (h1Match) {
      this.closeAllBlocks();
      this.appendSectionFootnotes();
      this.currentSectionLevel = 1;
      let metadata = {};

      // Look ahead for known metadata keys (author/date/institution/editor).
      // Unknown "key: value" lines are left in place to render as content.
      let k = index + 1;
      while (k < lines.length) {
        const nextLine = lines[k].trim();
        if (nextLine === '') { k++; continue; }
        const metaMatch = nextLine.match(CONFIG.PATTERNS.METADATA);
        if (metaMatch && CONFIG.METADATA_KEYS.includes(metaMatch[1].toLowerCase())) {
          metadata[metaMatch[1].toLowerCase()] = metaMatch[2];
          lines[k] = ''; // Consume line
          k++;
        } else { break; }
      }
      this.html += this.renderDocumentHeader(h1Match[1], metadata);
      return true;
    }

    const hMatch = line.match(CONFIG.PATTERNS.HEADING);
    if (hMatch) {
      this.closeAllBlocks();
      const level = hMatch[1].length;
      const text = hMatch[2];

      // Flush footnotes when section level changes appropriately
      if (level <= this.currentSectionLevel || this.currentSectionLevel >= 3) {
        this.appendSectionFootnotes();
      }
      this.currentSectionLevel = level;

      // Auto-numbering logic for H2 and H3; H4-H6 only get a unique anchor id
      let displayText = text;
      let id;
      if (level === 2) {
        this.chapterNum++; this.sectionNum = 0;
        displayText = `${this.chapterNum} ${text}`;
        id = `section-${this.chapterNum}-${this.sectionNum}`;
      } else if (level === 3) {
        this.sectionNum++;
        displayText = `${this.chapterNum}.${this.sectionNum} ${text}`;
        id = `section-${this.chapterNum}-${this.sectionNum}`;
      } else {
        id = `subsection-${++this.minorHeadingNum}`;
      }
      this.html += `<h${level} id="${id}">${this.escapeInline(displayText)}</h${level}>\n`;
      return true;
    }
    return false;
  }

  /**
   * Processes unordered and ordered lists, including nesting.
   * Uses adaptive indentation to prevent numbering gaps.
   * @private
   * @param {string} line - Current line.
   * @returns {boolean} - True if line was consumed.
   */
  processLists(line) {
    let match, type;
    const ulMatch = line.match(CONFIG.PATTERNS.LIST_UL);
    const olMatch = line.match(CONFIG.PATTERNS.LIST_OL);

    if (ulMatch) { match = ulMatch; type = 'ul'; }
    else if (olMatch) { match = olMatch; type = 'ol'; }
    else { return false; }

    const content = match[2];
    this.closeBlockquote(); this.closeAlert(); this.closeTable();

    const indent = match[1].length;

    // Adaptive indentation logic:
    // Instead of hardcoding "2 spaces = 1 level", we compare with the current stack
    let targetLevel = 0;

    if (this.state.listStack.length > 0) {
      // Find the deepest list in the stack that has indentation <= current line
      let bestMatchIndex = -1;

      for (let i = this.state.listStack.length - 1; i >= 0; i--) {
        const stackItem = this.state.listStack[i];
        if (indent > stackItem.indent) {
          // It's a child of this item -> Target is one level deeper
          bestMatchIndex = i + 1;
          break;
        } else if (indent === stackItem.indent) {
          // It's a sibling of this item -> Target is same level
          bestMatchIndex = i;
          break;
        }
      }

      // If indent is smaller than everything, it resets to root (level 0)
      if (bestMatchIndex === -1 && indent < this.state.listStack[0].indent) {
        targetLevel = 0;
      } else {
        // Default to calculated index, or 0 if stack was empty/logic fell through
        targetLevel = bestMatchIndex > -1 ? bestMatchIndex : 0;
      }
    }

    // Close nested levels if we need to go back up
    while (this.state.listStack.length > targetLevel + 1) {
      this.closeOneListLevel();
    }

    // Open new levels until the stack reaches targetLevel
    while (this.state.listStack.length <= targetLevel) {
      this.html += `<${type}>\n`;
      this.state.listStack.push({ type: type, indent: indent });
    }

    // Handle task list items [x]
    const taskMatch = content.match(CONFIG.PATTERNS.CHECKBOX);
    if (taskMatch) {
      const checked = taskMatch[1].toLowerCase() === 'x' ? 'checked' : '';
      const text = taskMatch[2];
      this.html += `<li class="task-list-item"><input type="checkbox" disabled ${checked}> ${this.escapeInline(text)}</li>\n`;
    } else {
      this.html += `<li>${this.escapeInline(content)}</li>\n`;
    }
    return true;
  }

  /**
   * Processes table rows, headers, and the alignment separator.
   * @private
   * @param {string} line - Current line.
   * @param {number} index - Current line index.
   * @param {string[]} lines - All lines.
   * @returns {boolean} - True if line was consumed.
   */
  processTables(line, index, lines) {
    if (!line.includes('|')) return false;
    const match = line.match(CONFIG.PATTERNS.TABLE_ROW);
    if (!match) return false;
    const cells = match[1].split('|').map(c => c.trim()).filter(c => c !== '');

    // Detect separator line |---|:--:|--:| and capture per-column alignment
    const isSeparator = cells.length > 0 && cells.every(c => /^:?-+:?$/.test(c));
    if (isSeparator) {
      this.state.tableAlign = cells.map(c => {
        const left = c.startsWith(':');
        const right = c.endsWith(':');
        if (left && right) return 'center';
        if (right) return 'right';
        if (left) return 'left';
        return '';
      });
      return true; // Consume the separator without emitting a row
    }

    this.closeList(); this.closeBlockquote(); this.closeAlert();
    if (!this.state.inTable) {
      this.state.inTable = true;
      // Look ahead to check if next line is separator (implies current is header)
      const nextLine = (index + 1 < lines.length) ? lines[index + 1] : '';
      if (nextLine.includes('|') && nextLine.includes('-')) {
        this.state.tableHeader = cells;
      } else {
        this.state.tableRows.push(cells);
      }
    } else {
      this.state.tableRows.push(cells);
    }
    return true;
  }

  /**
   * Processes blockquotes (>) and GitHub-style alerts.
   * Lines without ">" directly below an open block are treated as lazy continuations.
   * @private
   * @param {string} line - Current line.
   * @returns {boolean} - True if line was consumed.
   */
  processQuotesAndAlerts(line) {
    const isQuoteChar = line.startsWith('>');
    if (!isQuoteChar && !this.state.inAlert && !this.state.inBlockquote) return false;

    // Lazy continuation: keep the raw line when already inside a block
    const content = isQuoteChar ? line.slice(1).trim() : line;

    // Check if it's the start of an alert
    const alertMatch = content.match(CONFIG.PATTERNS.ALERT);
    if (alertMatch) {
      this.closeList(); this.closeAlert(); this.closeBlockquote();
      this.state.inAlert = true;
      this.state.alertType = alertMatch[1].toLowerCase();
      return true;
    }

    if (this.state.inAlert) { this.state.alertBuffer.push(content); return true; }

    // If not alert, assume blockquote
    this.closeList(); this.closeAlert();
    if (!this.state.inBlockquote) this.state.inBlockquote = true;
    this.state.blockquoteBuffer.push(content);
    return true;
  }

  /**
   * Processes standalone images (figures with captions).
   * Supports an optional trailing {width=...} attribute block.
   * @private
   * @param {string} line - Current line.
   * @returns {boolean} - True if line was consumed.
   */
  processStandaloneImage(line) {
    const match = line.match(CONFIG.PATTERNS.IMAGE);
    if (!match) return false;

    const [, alt, src, attrs] = match;
    const safeSrc = this.sanitizeUrl(src);
    if (!safeSrc) return false;

    this.closeAllBlocks();
    let style = '';
    if (attrs) {
      const w = attrs.match(/width\s*=\s*"?([^"}]+)"?/);
      if (w) {
        const dim = this.sanitizeDimension(w[1]);
        if (dim) style = ` style="width: ${dim};"`;
      }
    }
    this.html += `<figure class="image-figure">`;
    this.html += `<img src="${safeSrc}" alt="${this.escapeHTML(alt)}"${style}>`;
    if (alt && alt.trim()) {
      this.globalFigureNum++;
      this.html += `<figcaption>${CONFIG.STRINGS.FIG_PREFIX} ${this.globalFigureNum} ${this.escapeHTML(alt)}</figcaption>`;
    }
    this.html += `</figure>\n`;
    return true;
  }

  /**
   * Detects standalone YouTube or Vimeo links and converts them to responsive iframes.
   * @private
   * @param {string} line - Current line.
   * @returns {boolean} - True if line was consumed.
   */
  processMediaEmbeds(line) {
    const trimmed = line.trim();

    const ytMatch = trimmed.match(CONFIG.PATTERNS.VIDEO_YOUTUBE);
    if (ytMatch) {
      this.closeAllBlocks();
      this.html += this.renderVideoEmbed(
        `https://www.youtube.com/embed/${ytMatch[1]}`,
        'accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture'
      );
      return true;
    }

    const vimeoMatch = trimmed.match(CONFIG.PATTERNS.VIDEO_VIMEO);
    if (vimeoMatch) {
      this.closeAllBlocks();
      this.html += this.renderVideoEmbed(
        `https://player.vimeo.com/video/${vimeoMatch[1]}`,
        'autoplay; fullscreen; picture-in-picture'
      );
      return true;
    }

    return false;
  }

  /**
   * Detects lines starting with block-level HTML tags (dl, details, etc.)
   * and renders them directly without wrapping in <p> tags.
   * @private
   * @param {string} line - Current line.
   * @returns {boolean} - True if line was consumed.
   */
  processBlockHtml(line) {
    if (CONFIG.PATTERNS.BLOCK_HTML_START.test(line)) {
      this.closeList();
      this.closeTable();
      this.closeBlockquote();
      this.closeAlert();

      // SECURITY: still route through escapeInline for sanitization,
      // but skip the <p> wrapper.
      this.html += `${this.escapeInline(line)}\n`;
      return true;
    }
    return false;
  }

  /**
   * Closes paragraph-level blocks when a blank line is reached.
   * Code and math blocks never reach here: parse() buffers their lines first.
   * @private
   */
  processEmptyLine() {
    this.closeList(); this.closeTable(); this.closeBlockquote(); this.closeAlert();
  }

  // --- Closers & Rendering Helper Methods ---

  /**
   * Renders the buffered fenced code block into an HTML code container.
   * Maps common language aliases (js, py) to PrismJS class names.
   * @private
   */
  flushCodeBlock() {
    if (!this.state.inCodeBlock) return;
    const rawLang = this.state.codeLang.toLowerCase() || 'plaintext';
    // Map short codes to PrismJS classes
    const lang = rawLang === 'js' ? 'javascript' : rawLang === 'py' ? 'python' : rawLang;
    const langClass = ` class="language-${lang}"`;

    this.html += `<div class="code-block-container"><button class="copy-btn">${CONFIG.STRINGS.COPY}</button><pre><code${langClass}>`;
    this.html += this.state.codeBuffer.map(l => this.escapeHTML(l)).join('\n');
    this.html += `</code></pre></div>\n`;

    this.state.inCodeBlock = false; this.state.codeBuffer = []; this.state.codeLang = ''; this.state.codeFence = '';
  }

  /**
   * Renders the buffered math block via KaTeX in display mode.
   * @private
   */
  flushMathBlock() {
    if (!this.state.inMathBlock) return;
    const tex = this.state.mathBuffer.join('\n');
    this.html += this.renderKaTeX(tex, true);
    this.state.inMathBlock = false; this.state.mathBuffer = [];
  }

  /**
   * Closes one level of list nesting.
   * @private
   */
  closeOneListLevel() {
    if (this.state.listStack.length === 0) return;
    const item = this.state.listStack.pop();
    this.html += `</${item.type}>\n`;
  }

  /**
   * Closes all open lists.
   * @private
   */
  closeList() { while (this.state.listStack.length > 0) this.closeOneListLevel(); }

  /**
   * Renders the buffered table data, applying per-column alignment.
   * @private
   */
  closeTable() {
    if (!this.state.inTable) return;
    const alignAttr = (i) => this.state.tableAlign[i] ? ` style="text-align:${this.state.tableAlign[i]}"` : '';

    this.html += '<table>\n';
    if (this.state.tableHeader) {
      this.html += '<thead>\n<tr>\n';
      this.state.tableHeader.forEach((h, i) => this.html += `<th${alignAttr(i)}>${this.escapeInline(h)}</th>\n`);
      this.html += '</tr>\n</thead>\n';
    }
    if (this.state.tableRows.length > 0) {
      this.html += '<tbody>\n';
      this.state.tableRows.forEach(row => {
        this.html += '<tr>\n';
        row.forEach((cell, i) => this.html += `<td${alignAttr(i)}>${this.escapeInline(cell)}</td>\n`);
        this.html += '</tr>\n';
      });
      this.html += '</tbody>\n';
    }
    this.html += '</table>\n';
    this.state.inTable = false; this.state.tableHeader = null; this.state.tableRows = []; this.state.tableAlign = [];
  }

  /**
   * Renders buffered blockquote text.
   * @private
   */
  closeBlockquote() {
    if (!this.state.inBlockquote) return;
    this.html += '<blockquote>';
    this.html += this.renderBufferedParagraphs(this.state.blockquoteBuffer);
    this.html += '</blockquote>\n';
    this.state.inBlockquote = false; this.state.blockquoteBuffer = [];
  }

  /**
   * Renders buffered alert text with proper styling.
   * @private
   */
  closeAlert() {
    if (!this.state.inAlert) return;
    const title = CONFIG.STRINGS.ALERT_TITLES[this.state.alertType] || 'Alert';

    this.html += `<div class="alert alert-${this.state.alertType}">`;
    this.html += `<div class="alert-header"><span class="alert-title">${title}</span></div>`;
    this.html += `<div class="alert-content">`;
    this.html += this.renderBufferedParagraphs(this.state.alertBuffer);
    this.html += `</div></div>\n`;

    this.state.inAlert = false; this.state.alertBuffer = []; this.state.alertType = '';
  }

  /**
   * Closes all open block contexts. Called at EOF and before horizontal rules.
   * @private
   */
  closeAllBlocks() {
    this.flushCodeBlock(); this.flushMathBlock(); this.closeList();
    this.closeTable(); this.closeAlert(); this.closeBlockquote();
  }

  /**
   * Renders array of text lines as HTML paragraphs.
   * @private
   * @param {string[]} lines - Lines of text.
   * @returns {string} - HTML string.
   */
  renderBufferedParagraphs(lines) {
    let output = ''; let pBuffer = [];
    const flushP = () => {
      if (pBuffer.length > 0) {
        const text = pBuffer.map(l => this.escapeInline(l)).join(' ');
        output += `<p>${text}</p>`; pBuffer = [];
      }
    };
    lines.forEach(l => { if (l === '') flushP(); else pBuffer.push(l); });
    flushP();
    return output;
  }

  /**
   * Generates the document title block HTML.
   * @private
   * @param {string} title - The document title.
   * @param {DocumentMeta} meta - Optional metadata fields.
   * @returns {string} - HTML string.
   */
  renderDocumentHeader(title, meta) {
    let h = `<header class="document-header">\n`;
    h += `<h1>${this.escapeInline(title)}</h1>\n`;
    if (meta.author) h += `<div class="author">${this.escapeHTML(meta.author)}</div>\n`;
    if (meta.date) h += `<div class="date">${this.escapeHTML(meta.date)}</div>\n`;
    if (meta.institution) h += `<div class="institution">${this.escapeHTML(meta.institution)}</div>\n`;
    if (meta.editor) h += `<div class="editor">${CONFIG.STRINGS.EDITED_BY} ${this.escapeHTML(meta.editor)}</div>\n`;
    h += `</header>\n`;
    return h;
  }

  /**
   * Renders a responsive 16:9 iframe wrapper for an embedded video.
   * @private
   * @param {string} src - The embed URL of the video.
   * @param {string} allow - The iframe permissions policy.
   * @returns {string} - HTML string.
   */
  renderVideoEmbed(src, allow) {
    return `<div class="video-container" style="position:relative;padding-bottom:56.25%;height:0;overflow:hidden;margin-bottom:1.75rem;">
      <iframe
        src="${src}"
        style="position:absolute;top:0;left:0;width:100%;height:100%;border:0;border-radius:4px;"
        allow="${allow}"
        allowfullscreen
        loading="lazy">
      </iframe>
    </div>\n`;
  }

  /**
   * Generates the page footer HTML with project attribution links.
   * @private
   * @returns {string} - HTML string.
   */
  generateFooter() {
    const rel = 'rel="noopener noreferrer"';
    return `
    <footer class="markpaper-footer">
      <p id="generated-by">Generated by <a href="https://github.com/rubensbraz/MarkPaper" target="_blank" ${rel}>MarkPaper</a>.</p><br>
      <p><b>Original project: <a href="https://github.com/TetsuakiBaba/MarkPaper" target="_blank" ${rel}>MarkPaper (Tetsuaki Baba)</a>.</b></p>
      <p><b>Refactor (this version): <a href="https://github.com/rubensbraz/MarkPaper" target="_blank" ${rel}>MarkPaper (Rubens Braz)</a>.</b></p>
    </footer>`;
  }

  /**
   * Flushes accumulated footnotes for the current section into the HTML output.
   * @private
   */
  appendSectionFootnotes() {
    if (this.sectionFootnotes.length === 0) return;
    this.html += '<div class="footnotes">\n';
    this.sectionFootnotes.forEach(id => {
      if (this.footnotesDef[id]) {
        this.html += `<div class="footnote" id="footnote-${id}"><sup>${id}</sup> ${this.escapeInline(this.footnotesDef[id])}</div>\n`;
      }
    });
    this.html += '</div>\n';
    this.sectionFootnotes = [];
  }

  /**
   * Renders a TeX string via KaTeX, with a plain-text fallback when KaTeX is unavailable.
   * @private
   * @param {string} tex - LaTeX expression.
   * @param {boolean} [displayMode=false] - Whether to render in display (block) mode.
   * @returns {string} - HTML string.
   */
  renderKaTeX(tex, displayMode = false) {
    if (typeof katex === 'undefined') {
      // SECURITY: degrade to escaped plain text instead of injecting raw TeX
      const fallback = this.escapeHTML(tex);
      return displayMode ? `<pre>${fallback}</pre>` : `<code>${fallback}</code>`;
    }
    try {
      return katex.renderToString(tex, { displayMode: displayMode, throwOnError: false });
    } catch (e) {
      console.error('MarkPaper: KaTeX rendering failed', e);
      return `<span style="color:red">${CONFIG.STRINGS.MATH_ERROR}</span>`;
    }
  }

  // --- Sanitization & Escaping ---

  /**
   * Escapes basic HTML special characters to their entity equivalents.
   * @private
   * @param {string} text - Input string.
   * @returns {string} - HTML-safe string.
   */
  escapeHTML(text) {
    return text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&#39;');
  }

  /**
   * Checks whether a URL resolves to a dangerous protocol.
   * @private
   * @param {string} url - The URL to inspect.
   * @returns {boolean} - True if the URL must be blocked.
   */
  isDangerousUrl(url) {
    // SECURITY: decode HTML-entity obfuscation the way a browser would, then strip
    // whitespace and C0 control characters (codes <= 32) that browsers also ignore.
    const decoded = url
      .replace(/&#x([0-9a-f]+);?/gi, (m, code) => String.fromCharCode(parseInt(code, 16)))
      .replace(/&#(\d+);?/g, (m, code) => String.fromCharCode(parseInt(code, 10)))
      .replace(/&tab;|&newline;/gi, '')
      .replace(/&colon;/gi, ':');
    let cleaned = '';
    for (let i = 0; i < decoded.length; i++) {
      if (decoded.charCodeAt(i) > 32) cleaned += decoded[i];
    }
    return /^(javascript|vbscript|data|about):/i.test(cleaned);
  }

  /**
   * Sanitizes a URL for safe use in href/src attributes.
   * @private
   * @param {string} url - The raw URL.
   * @returns {string} - The attribute-safe URL, or an empty string when blocked.
   * @example
   * parser.sanitizeUrl('javascript:alert(1)'); // -> ''
   * parser.sanitizeUrl('https://example.com'); // -> 'https://example.com'
   */
  sanitizeUrl(url) {
    if (this.isDangerousUrl(url)) return '';
    return url.trim().replace(/"/g, '&quot;');
  }

  /**
   * Validates a CSS length used by the {width=...} image syntax.
   * @private
   * @param {string} value - The raw dimension string.
   * @returns {string} - The validated dimension, or an empty string when invalid.
   */
  sanitizeDimension(value) {
    const trimmed = value.trim();
    return CONFIG.PATTERNS.DIMENSION.test(trimmed) ? trimmed : '';
  }

  /**
   * Filters an inline `style` attribute down to an allowlist of safe properties.
   * SECURITY: drops position/inset overlays, url() trackers, and CSS expressions.
   * @private
   * @param {string} value - The raw style attribute value.
   * @returns {string} - The sanitized style declaration, or an empty string.
   */
  sanitizeStyle(value) {
    return value.split(';').map(decl => {
      const idx = decl.indexOf(':');
      if (idx < 0) return '';
      const prop = decl.slice(0, idx).trim().toLowerCase();
      const val = decl.slice(idx + 1).trim();
      if (!CONFIG.ALLOWED_STYLE_PROPS.includes(prop)) return '';
      if (/url\s*\(|expression\s*\(|javascript:|@import/i.test(val)) return '';
      return `${prop}: ${val}`;
    }).filter(Boolean).join('; ');
  }

  /**
   * Checks whether an <iframe> src points at an allowlisted embed host.
   * @private
   * @param {string} url - The iframe src value.
   * @returns {boolean} - True if the host is a permitted video provider over HTTPS.
   */
  isAllowedEmbedHost(url) {
    try {
      // Resolve against a sentinel base so relative URLs land on a blocked host.
      const u = new URL(url, 'https://markpaper.invalid');
      if (u.protocol !== 'https:') return false;
      return CONFIG.EMBED_HOST_ALLOWLIST.includes(u.hostname.toLowerCase());
    } catch (e) {
      return false;
    }
  }

  /**
   * Sanitizes an HTML string using an allowlist approach.
   * Removes disallowed tags, dangerous attributes (on*, javascript:, data:),
   * unsafe inline styles, and iframes that target non-allowlisted hosts.
   * @private
   * @param {string} text - Raw HTML string.
   * @returns {string} - Sanitized HTML string.
   */
  sanitizeHTML(text) {
    return text.replace(/<(\/?)([\w-]+)([^>]*)>/gi, (match, slash, tag, attrs) => {
      const tagLower = tag.toLowerCase();
      const escapeTag = () => match.replace(/</g, '&lt;').replace(/>/g, '&gt;');

      // Filter tag name
      if (!CONFIG.ALLOWED_TAGS.includes(tagLower)) return escapeTag();

      if (slash === '/') return `</${tag}>`;

      // SECURITY: only allow iframes that embed allowlisted video hosts
      if (tagLower === 'iframe') {
        const srcMatch = attrs.match(/\bsrc\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s>]+))/i);
        const src = srcMatch ? (srcMatch[1] || srcMatch[2] || srcMatch[3] || '') : '';
        if (!this.isAllowedEmbedHost(src)) return escapeTag();
      }

      let safeAttrs = '';
      if (attrs.trim()) {
        const attrMatches = attrs.match(/\s+([^=\s]+)(?:\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s>]+)))?/g);
        if (attrMatches) {
          attrMatches.forEach(attrMatch => {
            const parts = attrMatch.trim().match(/^([^=\s]+)(?:\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s>]+)))?$/);
            if (parts) {
              const name = parts[1].toLowerCase();
              let val = parts[2] || parts[3] || parts[4] || '';
              // Filter attribute name
              if (!CONFIG.ALLOWED_ATTRIBUTES.includes(name)) return;
              // SECURITY: filter dangerous protocols on URL-bearing attributes
              if ((name === 'href' || name === 'src') && this.isDangerousUrl(val)) return;
              // SECURITY: filter inline styles down to safe properties
              if (name === 'style') {
                val = this.sanitizeStyle(val);
                if (!val) return;
              }
              safeAttrs += ` ${name}="${val.replace(/"/g, '&quot;')}"`;
            }
          });
        }
      }
      return `<${tag}${safeAttrs}>`;
    });
  }

  /**
   * Parses inline Markdown syntax (bold, italic, links, etc.).
   * Uses protection maps to prevent recursive parsing of protected content
   * (math, valid HTML tags, and inline code spans).
   * @private
   * @param {string} text - The line text.
   * @returns {string} - HTML string.
   * @example
   * parser.escapeInline('**bold** and `code`');
   * // -> '<strong>bold</strong> and <code>code</code>'
   */
  escapeInline(text) {
    const mathMap = new Map(); let mCounter = 0;

    // Protect inline math ($...$)
    text = text.replace(/\$((?:[^\$]|\\\$)+)\$/g, (match, tex) => {
      const key = `${PH_OPEN}MATH${mCounter++}${PH_CLOSE}`;
      mathMap.set(key, this.renderKaTeX(tex, false));
      return key;
    });

    // Sanitize raw HTML
    let escaped = this.sanitizeHTML(text);

    // Protect valid HTML tags
    const tagMap = new Map(); let tCounter = 0;
    escaped = escaped.replace(/<(\/?)([\w-]+)([^>]*)>/g, (match, slash, tag) => {
      if (CONFIG.ALLOWED_TAGS.includes(tag.toLowerCase())) {
        const key = `${PH_OPEN}TAG${tCounter++}${PH_CLOSE}`;
        tagMap.set(key, match);
        return key;
      }
      return match;
    });

    // Escape special chars outside protected areas
    escaped = escaped.replace(/&(?![a-zA-Z0-9#]+;)/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

    // SECURITY: restore with a function replacer so "$" substitution patterns
    // inside the protected values are inert.
    tagMap.forEach((val, key) => { escaped = escaped.replace(key, () => val); });
    mathMap.forEach((val, key) => { escaped = escaped.replace(key, () => val); });

    // Protect inline code spans so their content skips Markdown and link parsing
    const codeMap = new Map(); let cCounter = 0;
    escaped = escaped.replace(/`([^`]+)`/g, (match, code) => {
      const key = `${PH_OPEN}CODE${cCounter++}${PH_CLOSE}`;
      codeMap.set(key, `<code>${code}</code>`);
      return key;
    });

    // Parse Markdown emphasis syntax
    escaped = escaped.replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>');
    escaped = escaped.replace(/\*(.+?)\*/g, '<em>$1</em>');
    escaped = escaped.replace(/~~(.+?)~~/g, '<s>$1</s>');

    // Images
    escaped = escaped.replace(/!\[([^\]]*)\]\(([^)]+)\)/g, (match, alt, src) => {
      const safeSrc = this.sanitizeUrl(src);
      return safeSrc ? `<img src="${safeSrc}" alt="${this.escapeHTML(alt)}">` : alt;
    });

    // Links
    escaped = escaped.replace(/\[([^\]]+)\]\(([^)]+)\)/g, (match, label, href) => {
      const safeHref = this.sanitizeUrl(href);
      return safeHref ? `<a href="${safeHref}" target="_blank" rel="noopener noreferrer">${label}</a>` : label;
    });

    // Footnote references
    escaped = escaped.replace(/\[\^([^\]]+)\]/g, (match, id) => {
      if (!this.sectionFootnotes.includes(id)) this.sectionFootnotes.push(id);
      return `<sup><a href="#footnote-${id}" class="footnote-ref">${id}</a></sup>`;
    });

    // Auto-link bare URLs; the two-alternative regex skips content inside HTML tags
    // to prevent wrapping URLs that already appear inside href/src attributes.
    escaped = escaped.replace(/(<[^>]+>)|((https?|ftp):\/\/[^\s<>"']+)/g, (match, tag, url) => {
      if (tag) return tag;
      return `<a href="${url}" target="_blank" rel="noopener noreferrer">${url}</a>`;
    });

    // Restore inline code spans
    codeMap.forEach((val, key) => { escaped = escaped.replace(key, () => val); });

    return escaped;
  }
}

