/**
 * Handles the settings modal, user preferences, and theme switching.
 * Public API: init(), toggle(), close().
 */
class SettingsController {
  /**
   * @param {MarkPaperUI} ui - Reference to the UI controller.
   */
  constructor(ui) {
    this.ui = ui;
    this.visible = false;
    this.prefs = this.loadPrefs();
  }

  /** Initializes settings modal and applies defaults. */
  init() {
    this.renderModal();
    this.applyPrefs();
  }

  /**
   * Loads preferences from LocalStorage, honoring the OS color scheme on first
   * visit and falling back to defaults on corrupted data.
   * @private
   * @returns {ThemePrefs} - The merged preferences object.
   */
  loadPrefs() {
    try {
      const saved = localStorage.getItem(CONFIG.STORAGE_KEYS.SETTINGS);
      if (saved) return { ...CONFIG.DEFAULTS, ...JSON.parse(saved) };
    } catch (e) {
      console.error('MarkPaper: failed to read saved settings', e);
    }
    // No saved preference: start from the operating system's color scheme.
    if (window.matchMedia && window.matchMedia('(prefers-color-scheme: dark)').matches) {
      return { ...CONFIG.DEFAULTS, ...CONFIG.DARK_PRESET };
    }
    return { ...CONFIG.DEFAULTS };
  }

  /**
   * Saves current preferences to LocalStorage and applies them.
   * @private
   */
  savePrefs() {
    try {
      localStorage.setItem(CONFIG.STORAGE_KEYS.SETTINGS, JSON.stringify(this.prefs));
    } catch (e) {
      console.error('MarkPaper: failed to save settings', e);
    }
    this.applyPrefs();
  }

  /**
   * Applies the current preferences to the CSS variables.
   * Also handles the dynamic switching of the PrismJS theme (Light/Dark).
   * @private
   */
  applyPrefs() {
    const root = document.documentElement;

    // Detect if dark mode is active based on the preset background color
    const isDark = this.prefs['--background-color'] === CONFIG.DARK_PRESET['--background-color'];

    // Toggle a class on body for specific CSS overrides (if needed)
    document.body.classList.toggle('theme-dark', isDark);

    // Dynamic PrismJS theme switching
    const prismLink = document.getElementById('prism-theme-link');
    if (prismLink) {
      prismLink.href = isDark ? CONFIG.PRISM_THEMES.DARK : CONFIG.PRISM_THEMES.LIGHT;
    }

    // Apply CSS variables to :root
    for (const [key, value] of Object.entries(this.prefs)) {
      if (key === '--current-font-family') {
        let stack = value;
        // Map short names to full font stacks
        if (value === 'serif') stack = 'var(--font-serif)';
        if (value === 'sans') stack = 'var(--font-sans-serif)';
        if (value === 'mono') stack = 'var(--font-monospace)';
        root.style.setProperty(key, stack);
      } else {
        root.style.setProperty(key, value);
      }
    }
  }

  /**
   * Generates the HTML for the settings modal.
   * @private
   */
  renderModal() {
    const modal = document.createElement('div');
    modal.className = 'settings-modal';
    modal.setAttribute('role', 'dialog');
    modal.setAttribute('aria-label', CONFIG.STRINGS.SETTINGS);
    modal.innerHTML = `
      <div class="settings-header">
        <h3>${CONFIG.STRINGS.SETTINGS}</h3>
        <button class="close-settings" aria-label="Close settings">&times;</button>
      </div>
      <div class="settings-body">

        <div class="setting-group">
            <label>Theme Preset</label>
            <div class="theme-buttons">
                <button class="btn-theme-light">Light</button>
                <button class="btn-theme-dark">Dark Mode</button>
            </div>
        </div>

        <div class="setting-group">
          <label>Font Size (<span id="fs-val">${this.prefs['--font-base-size']}</span>)</label>
          <input type="range" min="12" max="24" step="1" id="input-font-size" value="${parseInt(this.prefs['--font-base-size'], 10)}">
        </div>

        <div class="setting-group">
          <label for="input-font-family">Font Family</label>
          <select id="input-font-family">
            <option value="serif">Serif (Classic)</option>
            <option value="sans">Sans-Serif (Modern)</option>
            <option value="mono">Monospace (Code)</option>
          </select>
        </div>

        <div class="setting-group">
          <label for="input-bg-color">Background Color</label>
          <input type="color" id="input-bg-color" value="${this.prefs['--background-color']}">
        </div>

        <div class="setting-group">
          <label for="input-text-color">Text Color</label>
          <input type="color" id="input-text-color" value="${this.prefs['--text-color']}">
        </div>

        <div class="setting-group">
          <label for="input-accent-color">Link/Accent Color</label>
          <input type="color" id="input-accent-color" value="${this.prefs['--accent-color']}">
        </div>

        <div class="setting-actions">
            <button class="btn-reset">Reset Defaults</button>
        </div>
      </div>
    `;
    document.body.appendChild(modal);
    this.domModal = modal;
    this.bindEvents();
  }

  /**
   * Binds event listeners to the settings inputs.
   * @private
   */
  bindEvents() {
    this.domModal.querySelector('.close-settings').addEventListener('click', () => this.close());

    // Font size slider
    const fsInput = this.domModal.querySelector('#input-font-size');
    const fsDisplay = this.domModal.querySelector('#fs-val');
    fsInput.addEventListener('input', (e) => {
      const val = `${e.target.value}px`;
      this.prefs['--font-base-size'] = val;
      fsDisplay.textContent = val;
      this.savePrefs();
    });

    // Font family select
    const ffInput = this.domModal.querySelector('#input-font-family');
    const current = this.prefs['--current-font-family'];
    if (current === 'var(--font-sans-serif)' || current === 'sans') ffInput.value = 'sans';
    else if (current === 'var(--font-monospace)' || current === 'mono') ffInput.value = 'mono';
    else ffInput.value = 'serif';

    ffInput.addEventListener('change', (e) => {
      this.prefs['--current-font-family'] = e.target.value;
      this.savePrefs();
    });

    // Color pickers helper
    const bindColor = (id, key) => {
      const el = this.domModal.querySelector(id);
      el.addEventListener('input', (e) => {
        this.prefs[key] = e.target.value;
        this.savePrefs();
      });
      return el;
    };

    const bgInput = bindColor('#input-bg-color', '--background-color');
    const txtInput = bindColor('#input-text-color', '--text-color');
    const accInput = bindColor('#input-accent-color', '--accent-color');

    // Mirrors the current preferences back into the color picker inputs
    const syncColorInputs = () => {
      bgInput.value = this.prefs['--background-color'];
      txtInput.value = this.prefs['--text-color'];
      accInput.value = this.prefs['--accent-color'];
    };

    // Theme preset buttons
    this.domModal.querySelector('.btn-theme-dark').addEventListener('click', () => {
      Object.assign(this.prefs, CONFIG.DARK_PRESET);
      syncColorInputs();
      this.savePrefs();
    });

    this.domModal.querySelector('.btn-theme-light').addEventListener('click', () => {
      // Restore the defaults for every variable the dark preset overrides
      for (const key of Object.keys(CONFIG.DARK_PRESET)) {
        this.prefs[key] = CONFIG.DEFAULTS[key];
      }
      syncColorInputs();
      this.savePrefs();
    });

    // Reset all button
    this.domModal.querySelector('.btn-reset').addEventListener('click', () => {
      this.prefs = { ...CONFIG.DEFAULTS };
      fsInput.value = parseInt(CONFIG.DEFAULTS['--font-base-size'], 10);
      fsDisplay.textContent = CONFIG.DEFAULTS['--font-base-size'];
      ffInput.value = CONFIG.DEFAULTS['--current-font-family'];
      syncColorInputs();
      this.savePrefs();
    });
  }

  /** Toggles the visibility of the settings modal. */
  toggle() {
    this.visible = !this.visible;
    if (this.visible) {
      this.domModal.classList.add('open');
      this.ui.dom.overlay.classList.add('show');
    } else {
      this.close();
    }
  }

  /** Closes the settings modal. */
  close() {
    this.visible = false;
    this.domModal.classList.remove('open');
    if (!this.ui.dom.menu.classList.contains('open')) {
      this.ui.dom.overlay.classList.remove('show');
    }
  }
}

